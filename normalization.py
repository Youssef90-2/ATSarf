"""
normalization.py
================
الفكرة (Idea): تجهيز النص العربي قبل أي تحليل.

من الـ paper (§2, "Arabic morphological analysis"):
    التحليل الصرفي بيفترض إنو النص نظيف. الكلمة الوحدة ممكن يكون إلها
    كذا شكل بسبب التشكيل والهمزات، فلازم نوحّدها.

من النظام القديم (src/util/diacritics.h + letters.h):
    - isDiacritic(): بيتعرّف على كل علامات التشكيل ويشيلها.
    - letters.h: عرّف كل أشكال الألف والهمزة (alef, alef_hamza_above,
      alef_hamza_below, alef_madda_above, alef_wasla...) — لأنه لازم
      نوحّدها كلها لألف واحدة تا الأسماء تتطابق.

من داتاك الحقيقية (kafi1.txt):
    - رموز دخيلة: علامات اقتباس \" ، أقواس [ ] ( ) ، رمز التاريخ ه‍ (0x0647+0x200D).
    - النص شبه غير مشكّل، بس فيه تشكيل متفرق لازم يتشال.

--------------------------------------------------------------------------
النقطة الأهم في التصميم:
    النظام كلو بيشتغل على "مواقع الحروف" (offsets) في النص الأصلي
    (متل الكود القديم: NamePrim بيخزّن m_start/m_end، مش نسخة من الاسم).
    لهيك ما فينا نغيّر طول النص ونخرب المواقع.

    الحل: normalize() بترجّع:
        (1) النص المُنظّف
        (2) خريطة index_map: لكل حرف بالنص المنظّف، وين كان بالنص الأصلي.
    هيك نقدر نشتغل عالنص المنظّف، وبالآخر نرجّع المواقع للنص الأصلي.
--------------------------------------------------------------------------
"""

import unicodedata


# ---------------------------------------------------------------------------
# 1. علامات التشكيل (Diacritics) — نفس اللي كان النظام القديم يشيلها
#    (من letters.h: fatha, damma, kasra, sukun, التنوين, shadda, madda...)
# ---------------------------------------------------------------------------
DIACRITICS = {
    "\u064B",  # fathatayn   ً
    "\u064C",  # dammatayn   ٌ
    "\u064D",  # kasratayn   ٍ
    "\u064E",  # fatha       َ
    "\u064F",  # damma       ُ
    "\u0650",  # kasra       ِ
    "\u0651",  # shadda      ّ
    "\u0652",  # sukun       ْ
    "\u0653",  # madda       ٓ
    "\u0654",  # hamza above ٔ
    "\u0655",  # hamza below ٕ
    "\u0670",  # superscript alef (alef khanjariyya) ٰ
}

# محرف التطويل (tatweel / kashida) ـــ — حشو بصري، بينشال دايماً
TATWEEL = "\u0640"

# محرف الوصل غير المرئي (ZERO WIDTH JOINER) — بيجي مع "ه‍" رمز التاريخ بداتاك
ZERO_WIDTH_JOINER = "\u200D"


# ---------------------------------------------------------------------------
# 2. توحيد الحروف (Letter unification)
#    من الـ paper + النظام القديم: كل أشكال الألف والهمزة → ألف عادية،
#    تا "أحمد" و"احمد" و"إسحاق" و"اسحاق" يتطابقوا عند مقارنة الأسماء.
# ---------------------------------------------------------------------------
LETTER_MAP = {
    # كل أشكال الألف والهمزة → ا  (0x0627)
    "\u0623": "\u0627",  # أ  alef hamza above
    "\u0625": "\u0627",  # إ  alef hamza below
    "\u0622": "\u0627",  # آ  alef madda above
    "\u0671": "\u0627",  # ٱ  alef wasla
    "\u0649": "\u0627",  # ى  alef maksoura → ا  (النظام القديم كان يعتبرها شكل من الألف)

    # الهمزات المتوسطة/المنفصلة → ء  (توحيد بسيط، بيقلّل التنوّع)
    "\u0624": "\u0621",  # ؤ  waw hamza  → ء
    "\u0626": "\u0621",  # ئ  ya hamza   → ء

    # التاء المربوطة → هاء  (شائع في التطبيع العربي، والنظام القديم لمّح إلها)
    "\u0629": "\u0647",  # ة → ه
}


# ---------------------------------------------------------------------------
# 3. الرموز اللي بدنا نحوّلها لفراغ (من داتاك الحقيقية)
#    ملاحظة مهمة: منحوّلها لفراغ (مش نحذفها) تا نحافظ على طول النص واحد-لواحد
#    قدر الإمكان — بس حتى لو حذفنا، index_map بيمسك الموضوع.
# ---------------------------------------------------------------------------
SYMBOLS_TO_SPACE = set('"[](){}«»<>*')


def is_diacritic(ch: str) -> bool:
    """هل الحرف علامة تشكيل؟ (نفس فكرة isDiacritic في النظام القديم)."""
    return ch in DIACRITICS


def normalize(text: str):
    """
    تنضيف النص العربي مع الحفاظ على تتبّع المواقع الأصلية.

    بترجّع tuple:
        clean_text : النص بعد التنضيف
        index_map  : list بنفس طول clean_text، index_map[i] = موقع الحرف i
                     في النص الأصلي (text). ضروري تا نرجّع مواقع الرواة
                     للنص الأصلي بعد ما نخلص تحليل.

    خطوات التنضيف (بالترتيب):
        1. حذف علامات التشكيل + التطويل + محرف الوصل غير المرئي.
        2. توحيد الحروف (ألف/همزة/تاء مربوطة) عبر LETTER_MAP.
        3. تحويل الرموز الدخيلة ([ ] " ...) لفراغ.
        4. أي فراغ متتالي بيتحوّل لفراغ واحد (تبسيط للخطوات اللاحقة).
    """
    clean_chars = []
    index_map = []
    prev_was_space = False

    for original_pos, ch in enumerate(text):

        # (1) تشكيل / تطويل / وصل غير مرئي → بينشال تماماً
        if is_diacritic(ch) or ch == TATWEEL or ch == ZERO_WIDTH_JOINER:
            continue

        # (2) توحيد الحروف
        ch = LETTER_MAP.get(ch, ch)

        # (3) الرموز الدخيلة → فراغ
        if ch in SYMBOLS_TO_SPACE:
            ch = " "

        # (4) دمج الفراغات المتتالية بفراغ واحد
        if ch.isspace():
            if prev_was_space:
                continue          # تخطّي الفراغ الزائد
            ch = " "              # توحيد كل أنواع الفراغ (tab, newline...) لمسافة
            prev_was_space = True
        else:
            prev_was_space = False

        clean_chars.append(ch)
        index_map.append(original_pos)

    return "".join(clean_chars), index_map


def normalize_word(word: str) -> str:
    """
    نسخة مبسّطة لكلمة وحدة (بدون index_map).
    مفيدة لمقارنة كلمات المعجم (lexicons) والأسماء بسرعة.
    """
    clean, _ = normalize(word)
    return clean.strip()


