"""
lexicons.py
===========
الفكرة (Idea): القوائم المغلقة (Closed-class lexicons) — "حواس" النظام.

من الـ paper (§3.1):
    "ANGE also benefits from name connectors that denote family relations
     such as ibn (the child of)... In addition, it benefits from narration
     words which act as narrator connectors such as 3an (on behalf of) and
     hadat (narrated) and their morphological variations."

من النظام القديم (hadith_initialize في hadithCommon.cpp):
    1. ملف stop_words  → كلمات الرسول (بتنهي السند وبتبلّش المتن).
    2. ملف phrases     → عبارات التوقير المركّبة (عليه السلام...).
    3. كلمات مبنية حرف-حرف بالكود: حدث، عن، أبي، الرسول، وضمائر ه/هم/هما.
    4. استعلامات من قاعدة البيانات حسب "المعنى" (gloss):
       - NRC  : said / say / notify / listen / inform / narrate / from-about
       - عائلة: son / father / mother / grandfather / uncle ...
       نحنا منترجم هالمعاني لكلماتها العربية مباشرة (ما في DB بالنظام الجديد).

من داتاك الحقيقية (kafi1.txt):
    - "عدة من أصحابنا" (197 مرة!) و"بعض أصحابنا" → راوي جماعي بأول السند.
    - "وعنه" → سند مختصر بيرجع لراوي الحديث السابق.
    - "رفعه" → إسناد مرفوع (بيقفز رواة).

--------------------------------------------------------------------------
نقطة تصميم أساسية:
    كل القوائم مخزّنة "مُطبّعة" (بعد normalize_word) — لأنه النص اللي رح
    نفتّش فيه هو النص المُطبّع. مثلاً "أخبرنا" بالنص بتصير "اخبرنا"،
    فلازم القائمة تحتوي "اخبرنا". منكتب الكلمات بشكلها الطبيعي هون،
    والتطبيع بيصير أوتوماتيكياً عند تحميل الملف.
--------------------------------------------------------------------------
"""

from normalization import normalize_word


def _norm_set(words) -> frozenset:
    """بتطبّع كل كلمات القائمة مرة وحدة عند تحميل الملف."""
    return frozenset(normalize_word(w) for w in words)


# ===========================================================================
# 1. كلمات التحديث NRC (Narrator Connectors) — بتربط راوي براوي
#    المصدر: استعلام الـ DB القديم (said/inform/listen/narrate/from-about)
#            + الكلمات الحرفية hadath و _3an من hadithCommon.cpp:98,108
#    ملاحظة: منخزّن "جذوع" الأفعال، والمطابقة بالبادئة (startswith) بتغطي
#    كل التصريفات: حدثنا/حدثني/حدثتهم كلها بتبلش بـ"حدث" — نفس فكرة
#    الـ stem بالنظام القديم والـ paper ("and their morphological variations").
# ===========================================================================

# جذوع أفعال التحديث (بتغطي: حدثنا، حدثني، أخبرنا، أنبأنا، سمعت، روى...)
NRC_VERB_STEMS = _norm_set({
    "حدث",     # حدثنا / حدثني / حدثتهم   (hadath بالنظام القديم)
    "اخبر",    # أخبرنا / أخبرني           (inform)
    "انبا",    # أنبأنا / أنبأني           (notify — بعد التطبيع: انبا)
    "نبا",     # نبّأنا
    "سمع",     # سمعت / سمعنا              (listen)
    "روى",     # روى / رواه                (narrate)
    "روي",     # روي عن
    "ذكر",     # ذكر / ذكره
})

# كلمات ربط قائمة بذاتها (مطابقة كاملة، مش بادئة)
NRC_PARTICLES = _norm_set({
    "عن",      # الأهم بالكافي — العنعنة   (_3an بالنظام القديم :108)
    "قال",     # said — بيربط وبيبلّش المتن كمان
    "يقول",
})

# من داتاك: إسناد مرفوع/مختصر
NRC_SPECIAL = _norm_set({
    "رفعه",    # "رفعه إلى أبي عبد الله" — إسناد بيقفز رواة
    "يرفعه",
    "باسناده", # بإسناده
})


# ===========================================================================
# 2. روابط الأسماء NMC (Name Connectors) — بتبني الاسم المركّب
#    المصدر: استعلامات العائلة بالقديم (son/father/mother/uncle...)
#            + IBN/AB/OM_descriptions المنفصلة (لأنه الـ FSM بيفرّق بيناتهن)
# ===========================================================================

# "ابن" وأشكالها — IBN_descriptions بالقديم (أهم رابط: بيدل على الأبوّة)
IBN_WORDS = _norm_set({
    "بن", "ابن", "ابنه",
    "بنت", "ابنة",          # للراويات
})

# "أب" وأشكالها — AB_descriptions بالقديم (بتبلّش الكنية: أبو جعفر)
AB_WORDS = _norm_set({
    "ابو", "ابي", "ابا",     # أبو/أبي/أبا (حالات الإعراب الثلاث)
})

# "أم" وأشكالها — OM_descriptions بالقديم
OM_WORDS = _norm_set({
    "ام",                    # أم سلمة...
})

# باقي روابط العائلة — familyNMC_descriptions بالقديم
# (grandfather/grandmother/uncle/father-in-law...)
FAMILY_WORDS = _norm_set({
    "جد", "جده", "جدته",     # عن جده
    "عم", "عمه",             # عن عمه
    "خال", "خاله",           # عن خاله
    "اخو", "اخي", "اخيه",    # أخو فلان
    "مولى", "مولي",          # مولى فلان (شائعة بأسماء الرواة)
})

# كل روابط الأسماء مجموعة (للفحص السريع "هل الكلمة رابط اسم؟")
ALL_NMC_WORDS = IBN_WORDS | AB_WORDS | OM_WORDS | FAMILY_WORDS


# ===========================================================================
# 3. كلمات الرسول والمعصومين (Rasoul words) — بتنهي السند
#    المصدر: ملف stop_words بالقديم (منقول حرفياً) + alrasoul المبنية بالكود
#    + إضافات من داتاك (الكافي بيسند للأئمة: أبي عبد الله، أبي جعفر...)
# ===========================================================================

# من ملف stop_words القديم — حرفياً
RASOUL_WORDS = _norm_set({
    "رسول الله",
    "الرسول",
    "النبي",
    "ص",                     # اختصار صلى الله عليه وسلم
})

# عبارات التوقير — من ملف phrases القديم حرفياً + شائع بداتاك
HONORIFIC_PHRASES = _norm_set({
    "صلى الله عليه وسلم",
    "صلى الله عليه وعلى اله",
    "صلى الله عليه واله",
    "عليه السلام",
    "عليهم السلام",
    "عليهما السلام",
    "عليها السلام",          # إضافة: للسيدة فاطمة (موجودة بداتاك)
    "رضي الله عنه",
    "رضي الله عنها",         # إضافة
    "رضي الله عنهما",        # إضافة
    "رحمه الله",             # إضافة: موجودة بداتاك
})

# نهايات سند خاصة بالكافي (من داتاك): السند بينتهي عند الإمام بكنيته
# "عن أبي عبد الله عليه السلام قال:" — 339 مرة بـ kafi1!
IMAM_KUNYA_ENDINGS = _norm_set({
    "ابي عبد الله",          # الإمام الصادق
    "ابي جعفر",              # الإمام الباقر
    "ابي الحسن",             # الإمام الكاظم/الرضا
    "ابي ابراهيم",           # الإمام الكاظم
    "ابي محمد",              # الإمام العسكري
})


# ===========================================================================
# 4. الرواة الجماعيون (Compound narrators) — من داتاك، خصوصية الكافي
#    "عدة من أصحابنا عن أحمد بن محمد" — العدة = مجموعة رواة كراوي واحد
# ===========================================================================
COMPOUND_NARRATORS = _norm_set({
    "عدة من اصحابنا",
    "بعض اصحابنا",
    "غير واحد",
    "جماعة",
})


# ===========================================================================
# 5. ضمائر الراوي النسبي (Relative narrator) — من النظام القديم
#    suffixNames بالقديم (hadithCommon.cpp:104-106): ه / هم / هما
#    "عن أبيه" = عن أبي + ضمير → راوي معروف نسبةً لراوي قبلو
#    (وهيدا نفس الشي اللي equalNew بالقديم كان يرجّع 0 لأنه ما منعرف مين هو بعد)
# ===========================================================================
RELATIVE_SUFFIXES = _norm_set({
    "ه", "هم", "هما",
})

RELATIVE_NARRATOR_WORDS = _norm_set({
    "ابيه",                  # عن أبيه (أبي + ه) — abyi بالقديم :103
    "ابيهم", "ابيهما",
    "جده",                   # عن جدّه
    "عنه",                   # "وعنه" — سند مختصر بيرجع للراوي السابق (من داتاك)
})


# ===========================================================================
# 6. بدايات المتن (Matn cues) — إشارات إنو السند خلص والمحتوى بلّش
#    من بنية الحديث بالـ paper (sanad → matn) + داتاك
# ===========================================================================
MATN_CUE_WORDS = _norm_set({
    "قال",                   # "...عليه السلام قال: لما خلق الله..."
    "قالت",
    "يقول",
    "سالته",                 # سألته عن...
    "قلت",                   # قلت له...
    "كتبت",                  # كتبت إليه...
})


# ===========================================================================
# دوال فحص بسيطة — هيدول اللي رح يستعملهن engine.py والـ FSM
# ===========================================================================

def is_nrc_word(word: str) -> bool:
    """هل الكلمة كلمة تحديث (بتربط راوي براوي)؟"""
    w = normalize_word(word)
    if w in NRC_PARTICLES or w in NRC_SPECIAL:
        return True
    # مطابقة الجذع: حدثنا بتبلش بـ حدث (نفس فكرة stem القديم)
    return any(w.startswith(stem) for stem in NRC_VERB_STEMS)


def is_nmc_word(word: str) -> bool:
    """هل الكلمة رابط اسم (بن/أبو/أم/عائلة)؟"""
    return normalize_word(word) in ALL_NMC_WORDS


def is_ibn_word(word: str) -> bool:
    """هل الكلمة من عائلة (ابن)؟ — الـ FSM بيحتاج التمييز (أبوّة)."""
    return normalize_word(word) in IBN_WORDS


def is_ab_word(word: str) -> bool:
    """هل الكلمة من عائلة (أبو)؟ — بداية كنية."""
    return normalize_word(word) in AB_WORDS


def is_om_word(word: str) -> bool:
    """هل الكلمة من عائلة (أم)؟"""
    return normalize_word(word) in OM_WORDS


def is_rasoul_word(text_piece: str) -> bool:
    """هل المقطع كلمة/عبارة رسول أو توقير؟ (بتنهي السند)"""
    p = normalize_word(text_piece)
    return p in RASOUL_WORDS or p in HONORIFIC_PHRASES


def is_relative_narrator(word: str) -> bool:
    """هل الكلمة راوي نسبي (أبيه/جده/عنه)؟"""
    return normalize_word(word) in RELATIVE_NARRATOR_WORDS


def find_phrases_in(text: str, phrases: frozenset) -> list:
    """
    بتدوّر على عبارات مركّبة (متل 'عدة من اصحابنا' أو 'عليه السلام')
    جوّات نص مُطبّع، وبترجّع [(start, end, phrase), ...].

    ملاحظتين:
    1. النص لازم يكون مُطبّع قبل (من normalization.normalize).
    2. المطابقة على "حدود كلمات": قبل العبارة وبعدها لازم فراغ أو ترقيم
       أو طرف النص — تا ما يتطابق 'ص' جوّات 'اصحابنا' مثلاً.
    """
    def is_boundary(ch: str) -> bool:
        """الحرف بيعتبر حدّ كلمة إذا مش حرف/رقم (فراغ، ترقيم، :، ...)."""
        return not ch.isalnum()

    found = []
    n = len(text)
    for phrase in phrases:
        start = 0
        while True:
            pos = text.find(phrase, start)
            if pos == -1:
                break
            end = pos + len(phrase)
            # فحص حدود الكلمة عاليمين وعاليسار
            left_ok = (pos == 0) or is_boundary(text[pos - 1])
            right_ok = (end == n) or is_boundary(text[end])
            if left_ok and right_ok:
                found.append((pos, end, phrase))
            start = pos + 1
    return sorted(found)


